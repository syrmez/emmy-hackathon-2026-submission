// Node 22+ and Chrome; no npm packages. Start server.py first. Exercises real GPU inference.
import {spawn} from 'node:child_process';
import {mkdtempSync, readFileSync, existsSync, writeFileSync, rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {once} from 'node:events';
import assert from 'node:assert/strict';
const url=process.env.DEMO_URL||'http://127.0.0.1:8766';
const chrome=process.env.CHROME||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const profile=mkdtempSync(join(tmpdir(),'emmy-mnist-browser-'));
const browser=spawn(chrome,['--headless=new','--no-first-run','--no-default-browser-check','--disable-background-networking','--remote-debugging-port=0',`--user-data-dir=${profile}`,'about:blank'],{stdio:'ignore'});
const exited=once(browser,'exit'), sleep=ms=>new Promise(resolve=>setTimeout(resolve,ms));
let ws;
try{
  for(let i=0;!existsSync(join(profile,'DevToolsActivePort'))&&i<100;i++)await sleep(100);
  const port=readFileSync(join(profile,'DevToolsActivePort'),'utf8').split('\n')[0];
  const pages=await(await fetch(`http://127.0.0.1:${port}/json`)).json();
  ws=new WebSocket(pages.find(p=>p.type==='page').webSocketDebuggerUrl);await once(ws,'open');
  let next=0;const pending=new Map(),errors=[];
  ws.addEventListener('message',event=>{const message=JSON.parse(event.data);if(message.method==='Runtime.exceptionThrown')errors.push(message.params.exceptionDetails);if(pending.has(message.id)){const [resolve,reject]=pending.get(message.id);pending.delete(message.id);message.error?reject(Error(JSON.stringify(message.error))):resolve(message.result);}});
  const call=(method,params={})=>new Promise((resolve,reject)=>{const id=++next;pending.set(id,[resolve,reject]);ws.send(JSON.stringify({id,method,params}));});
  const evaluate=async expression=>{const response=await call('Runtime.evaluate',{expression,returnByValue:true,awaitPromise:true});assert.ok(!response.exceptionDetails,JSON.stringify(response.exceptionDetails));return response.result.value;};
  const wait=async(expression,seconds=20)=>{for(let i=0;i<seconds*10;i++){if(await evaluate(expression))return;await sleep(100);}throw Error('Timed out: '+expression);};
  const screenshot=async name=>writeFileSync(join(tmpdir(),name),Buffer.from((await call('Page.captureScreenshot',{format:'png'})).data,'base64'));
  await call('Page.enable');await call('Runtime.enable');
  await call('Emulation.setDeviceMetricsOverride',{width:1440,height:1100,deviceScaleFactor:1,mobile:false});
  await call('Page.navigate',{url});await wait('typeof model!=="undefined"&&!!model');
  assert.equal(await evaluate('$("lesson").hidden'),true);
  assert.equal(await evaluate('document.querySelectorAll(".kernel-card").length'),4);
  assert.equal(await evaluate('document.querySelectorAll("#samples button").length'),10);
  await evaluate('$("samples").children[7].click()');await wait('!busy&&result!==null',90);
  assert.equal(await evaluate('result.prediction'),7);
  assert.equal(await evaluate('records.filter(Boolean).length'),4);
  assert.equal(await evaluate('document.querySelectorAll(".kernel-card.done").length'),4);
  assert.equal(await evaluate('document.querySelectorAll(".probability.winner").length'),1);
  assert.ok(await evaluate('result.gpu_us>0'));
  await screenshot('emmy-mnist-desktop.png');
  await evaluate('$("education").click();selectKernel(0)');
  assert.equal(await evaluate('$("lesson").hidden'),false);
  assert.match(await evaluate('$("activation-title").textContent'),/1024/);
  await evaluate('$("next").click()');assert.equal(await evaluate('selected'),1);
  assert.match(await evaluate('$("activation-title").textContent'),/128/);
  await evaluate('document.querySelector("[data-highlight=math]").click()');
  assert.ok(await evaluate('document.querySelectorAll(".marked").length>0'));
  await evaluate('document.querySelector("[data-view=ir]").click()');
  assert.match(await evaluate('$("code").textContent'),/Tile/);
  await evaluate('document.querySelector("[data-view=source]").click()');
  assert.match(await evaluate('$("code").textContent'),/torch.relu/);
  await evaluate('document.querySelector("[data-view=ptx]").click();$("lesson").scrollIntoView()');
  await screenshot('emmy-mnist-step-through.png');
  await evaluate('$("education").click();$("clear").click();window.scrollTo(0,0)');
  assert.equal(await evaluate('latestPixels===null&&$("guess").textContent==="—"'),true);
  // Exercise real pointer handlers, MNIST preprocessing and a hand-drawn prediction.
  const rect=await evaluate('(()=>{const r=$("draw").getBoundingClientRect();return {x:r.x,y:r.y,width:r.width,height:r.height}})()');
  await call('Input.dispatchMouseEvent',{type:'mousePressed',x:rect.x+80,y:rect.y+60,button:'left',clickCount:1});
  for(const [x,y] of [[180,60],[165,90],[150,120],[135,150],[120,180],[105,210]])await call('Input.dispatchMouseEvent',{type:'mouseMoved',x:rect.x+x,y:rect.y+y,button:'left',buttons:1});
  await call('Input.dispatchMouseEvent',{type:'mouseReleased',x:rect.x+105,y:rect.y+210,button:'left',clickCount:1});
  await evaluate('clearTimeout(timer)');
  assert.equal(await evaluate('latestPixels.length'),784);
  assert.ok(await evaluate('latestPixels.every(v=>Number.isFinite(v)&&v>=0&&v<=1)&&latestPixels.some(v=>v>0)'));
  const center=await evaluate('(()=>{const mass=latestPixels.reduce((a,b)=>a+b,0);return [latestPixels.reduce((s,v,i)=>s+v*(i%28),0)/mass,latestPixels.reduce((s,v,i)=>s+v*Math.floor(i/28),0)/mass]})()');
  assert.ok(center.every(v=>Math.abs(v-13.5)<1),JSON.stringify(center));
  await evaluate('run()');
  assert.equal(await evaluate('result.prediction'),7,'The pointer-drawn seven should be recognized');
  await screenshot('emmy-mnist-drawing.png');
  await evaluate('resetResult()');
  // Controlled transport only for failure/stale-response paths; never used by the application.
  await evaluate('window.realFetch=window.fetch;window.fetch=async()=>new Response(JSON.stringify({type:"error",message:"runner offline <img src=x>"})+"\\n",{status:200});run()');
  await wait('!busy');
  assert.match(await evaluate('$("status").textContent'),/Inference failed/);
  assert.equal(await evaluate('$("guess").textContent'),'—');
  assert.equal(await evaluate('document.querySelectorAll("img").length'),0);
  await evaluate(`window.fetch=async()=>new Response(new ReadableStream({start(controller){window.finishTest=()=>{controller.enqueue(new TextEncoder().encode(JSON.stringify({type:'result',prediction:9,probabilities:Array(10).fill(.1),gpu_us:1})+'\\n'));controller.close();};}}));run();void 0`);
  await wait('busy&&!!window.finishTest');
  await evaluate('$("clear").click();window.finishTest()');await wait('!busy');
  assert.equal(await evaluate('$("guess").textContent'),'—','A stale result must not repopulate a cleared canvas');
  await evaluate('window.fetch=window.realFetch');
  await call('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true});
  await evaluate('window.scrollTo(0,0)');
  assert.ok(await evaluate('document.documentElement.scrollWidth<=390'));
  await screenshot('emmy-mnist-mobile.png');
  assert.deepEqual(errors,[]);
  console.log('PASS: real streamed GPU inference, PTX/IR/source tabs, optional step-through, returned tensors, pointer drawing, centering, clear/stale/failure states, mobile overflow, no JS errors');
  console.log(`Screenshots: ${tmpdir()}/emmy-mnist-{desktop,step-through,drawing,mobile}.png`);
}finally{ws?.close();browser.kill();await Promise.race([exited,sleep(5000)]);rmSync(profile,{recursive:true,force:true});}
